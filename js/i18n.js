let lang = 'ru';

export function resolveLang(sdkLang) {
  const code = String(sdkLang || 'ru').toLowerCase().slice(0, 2);
  if (code === 'ru' || code === 'en') return code;
  if (['be', 'kk', 'uk', 'uz'].includes(code)) return 'ru';
  return 'en';
}

export function initI18n(sdkLang) {
  lang = resolveLang(sdkLang);
  document.documentElement.lang = lang;
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ru';
  document.documentElement.lang = lang;
  return lang;
}

export function getLang() {
  return lang;
}

export function t(key) {
  return STRINGS[lang]?.[key] ?? STRINGS.ru[key] ?? key;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  document.title = t('game.title');
}

export function fishName(fish) {
  return lang === 'en' ? fish.nameEn : fish.nameRu;
}
